#!/usr/bin/env python3
"""Generates src/pdf/widths.rs: Helvetica / Helvetica-Bold advance widths (1/1000 em) for
WinAnsi codes 0..255. Liberation Sans is metric-compatible with Helvetica/Arial, so its advances
are Helvetica's. Usage: gen-widths.py <LiberationSans-Regular.ttf> <LiberationSans-Bold.ttf> > src/pdf/widths.rs"""
import sys
from fontTools.ttLib import TTFont

def table(path):
    f = TTFont(path); cmap = f.getBestCmap(); upm = f['head'].unitsPerEm; hmtx = f['hmtx']
    out = []
    for code in range(256):
        try: ch = bytes([code]).decode('cp1252')
        except UnicodeDecodeError: out.append(0); continue
        g = cmap.get(ord(ch))
        out.append(round(hmtx[g][0] * 1000 / upm) if g and code >= 32 else 0)
    return out

print("// @generated by tools/gen-widths.py from Liberation Sans (metric-compatible with Helvetica). Do not edit.")
for name, p in (("HELVETICA", sys.argv[1]), ("HELVETICA_BOLD", sys.argv[2])):
    t = table(p)
    print(f"pub const {name}: [u16; 256] = [")
    for i in range(0, 256, 16): print("    " + ", ".join(str(x) for x in t[i:i+16]) + ",")
    print("];")
